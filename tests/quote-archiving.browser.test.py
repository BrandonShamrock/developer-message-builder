"""Archive UI regressions against Vite and the existing in-memory backend."""
from pathlib import Path
import re
import fitz
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parent
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.route(re.compile(r'.*/src/supabase\.js(?:\?.*)?$'),lambda route:route.fulfill(status=200,content_type='application/javascript',body=(ROOT/'browser-fixture.js').read_text()))
    page.goto('http://127.0.0.1:5173/')
    page.get_by_role('button',name='Quotes',exact=True).click()
    page.get_by_role('button',name='Create Quote',exact=True).click()
    page.get_by_label('Select Client',exact=True).select_option('client')
    page.get_by_role('button',name='Add Product',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_role('checkbox').first.check()
    dialog.get_by_role('button',name='Add Selected Products',exact=True).click()
    page.get_by_label('Service overview',exact=True).fill('Preserve this saved service overview.')
    page.get_by_label('Expiry date',exact=True).fill('2026-12-15')
    page.get_by_role('button',name='Save Quote',exact=True).click()
    expect(dialog.locator('.quote-final-totals strong')).to_have_text(['R1,552.50','R776.25'])
    page.evaluate("async()=>{await Promise.all([...document.querySelectorAll('#quote-print img')].map(i=>i.decode()));await document.fonts.ready}")
    page.pdf(path='/tmp/archive-before.pdf',format='A4')
    dialog.get_by_role('button',name='Close Preview',exact=True).click()
    original=page.evaluate('JSON.parse(JSON.stringify(window.__db.crm_quotes[0]))')
    draft=page.locator('.crm-card').filter(has=page.get_by_role('heading',name=original['quote_number'],exact=True))
    expect(page.get_by_label('Show archived quotes',exact=True)).not_to_be_checked()
    # Cancellation never submits an archive request.
    page.once('dialog',lambda d:d.dismiss())
    draft.get_by_role('button',name='Archive',exact=True).click()
    expect(draft).to_be_visible()
    assert page.evaluate('window.__archiveCalls||0')==0
    # Failure is visible and leaves the saved quote present and unchanged.
    page.evaluate("window.__fail='set_crm_quote_archived'")
    page.once('dialog',lambda d:d.accept())
    draft.get_by_role('button',name='Archive',exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('Unable to archive quotation: Simulated RPC failure')
    expect(draft).to_be_visible()
    page.evaluate('window.__fail=null;window.__archiveDelay=500')
    page.once('dialog',lambda d:d.accept())
    draft.get_by_role('button',name='Archive',exact=True).click()
    expect(draft.get_by_role('button',name='Archive',exact=True)).to_be_disabled()
    draft.get_by_role('button',name='Archive',exact=True).evaluate('(e)=>{e.click();e.click()}')
    expect(draft).to_have_count(0)
    assert page.evaluate('window.__archiveCalls')==1
    expect(page.get_by_role('status')).to_contain_text('Quotation archived')
    page.get_by_label('Show archived quotes',exact=True).check()
    expect(draft.get_by_text('Archived',exact=True)).to_be_visible()
    expect(draft.get_by_role('button',name='Edit',exact=True)).to_be_disabled()
    expect(draft.get_by_role('button',name='Restore',exact=True)).to_be_enabled()
    for term in [original['quote_number'],'alpha dealer','TEAM GROUP']:
        page.get_by_label('Search quotations',exact=True).fill(term)
        expect(draft).to_be_visible()
    page.get_by_label('Search quotations',exact=True).fill('no matching quote')
    expect(draft).to_have_count(0)
    page.get_by_label('Search quotations',exact=True).fill('')
    draft.get_by_role('button',name='View',exact=True).click()
    expect(dialog.locator('.meta')).to_contain_text('2026/12/15')
    expect(dialog.locator('.quote-final-totals strong')).to_have_text(['R1,552.50','R776.25'])
    expect(dialog.get_by_role('button',name='Print / Save as PDF',exact=True)).to_be_enabled()
    page.evaluate("async()=>{await Promise.all([...document.querySelectorAll('#quote-print img')].map(i=>i.decode()));await document.fonts.ready}")
    page.pdf(path='/tmp/archive-after.pdf',format='A4')
    with fitz.open('/tmp/archive-before.pdf') as before, fitz.open('/tmp/archive-after.pdf') as after:
        assert ''.join(p.get_text() for p in before)==''.join(p.get_text() for p in after)
    dialog.get_by_role('button',name='Close Preview',exact=True).click()
    # A failed restore stays archived; a successful one updates the card immediately.
    page.evaluate("window.__fail='set_crm_quote_archived'")
    draft.get_by_role('button',name='Restore',exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('Unable to restore quotation')
    expect(draft.get_by_text('Archived',exact=True)).to_be_visible()
    page.evaluate('window.__fail=null;window.__archiveDelay=0')
    draft.get_by_role('button',name='Restore',exact=True).click()
    expect(page.get_by_role('status')).to_have_text('Quotation restored.')
    expect(draft.get_by_role('button',name='Edit',exact=True)).to_be_enabled()
    restored=page.evaluate('JSON.parse(JSON.stringify(window.__db.crm_quotes[0]))')
    restored.pop('is_archived',None)
    assert restored=={k:v for k,v in original.items() if k!='is_archived'}
    page.get_by_label('Show archived quotes',exact=True).uncheck()
    expect(draft).to_be_visible()
    draft.get_by_role('button',name='Edit',exact=True).click()
    expect(page.get_by_label('Service overview',exact=True)).to_have_value(original['service_overview'])
    expect(page.get_by_label('Expiry date',exact=True)).to_have_value(original['valid_until'])
    page.get_by_role('button',name='Save Quote',exact=True).click()
    expect(dialog.locator('.quote-final-totals strong')).to_have_text(['R1,552.50','R776.25'])
    dialog.get_by_role('button',name='Close Preview',exact=True).click()
    print('PASS draft confirmation/cancel/errors/duplicate prevention/filter/search/restore/save and identical archived PDF')
    # Seed an issued snapshot and reload data through navigation.
    page.evaluate("""() => {
      const q=structuredClone(window.__db.crm_quotes[0]);q.id='issued';q.quote_number='ISSUED-ARCHIVE';q.status='issued';q.is_archived=false;
      window.__db.crm_quotes.push(q);localStorage.setItem('amper-test-db',JSON.stringify(window.__db));
    }""")
    page.get_by_role('button',name='Dashboard',exact=True).click()
    page.get_by_role('button',name='Quotes',exact=True).click()
    issued=page.locator('.crm-card').filter(has=page.get_by_role('heading',name='ISSUED-ARCHIVE',exact=True))
    expect(issued.get_by_role('button',name='Edit',exact=True)).to_be_disabled()
    page.once('dialog',lambda d:d.accept())
    issued.get_by_role('button',name='Archive',exact=True).click()
    expect(issued).to_have_count(0)
    expect(draft).to_be_visible()
    page.get_by_label('Show archived quotes',exact=True).check()
    expect(page.locator('.crm-card')).to_have_count(2)
    expect(issued.get_by_text('Archived',exact=True)).to_be_visible()
    issued.get_by_role('button',name='View',exact=True).click()
    expect(dialog.locator('.quote-final-totals strong')).to_have_text(['R1,552.50','R776.25'])
    dialog.get_by_role('button',name='Close Preview',exact=True).click()
    page.reload()
    page.get_by_role('button',name='Quotes',exact=True).click()
    expect(issued).to_have_count(0)
    page.get_by_label('Show archived quotes',exact=True).check()
    issued.get_by_role('button',name='Restore',exact=True).click()
    expect(issued.get_by_role('button',name='Edit',exact=True)).to_be_disabled()
    expect(issued.get_by_text('Archived',exact=True)).to_have_count(0)
    assert page.evaluate("window.__db.crm_quotes.find(q=>q.id==='issued').status")=='issued'
    assert not errors,errors
    print('PASS issued archive/restore, persistence, both visibility states and issued read-only protection')
    browser.close()
